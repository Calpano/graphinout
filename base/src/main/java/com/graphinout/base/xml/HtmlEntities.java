    /**
     * Map of HTML entities to their Unicode code points, excluding the 5 XML entities. Source:
     * <a href="https://html.spec.whatwg.org/multipage/named-characters.html">HTML Living Standard</a>. This list is
     * comprehensive as of September 2025.
     * <p>
     * Thread-safe: built once in the holder's static initializer (the JVM runs it exactly once, and no thread can read
     * the table before it is complete) and never modified afterwards. Readers on many threads share it.
     */
    private static final class Holder {
        static final Map<String, int[]> ENTITIES = build();
    }

    public static boolean contains(String name) {
        return Holder.ENTITIES.containsKey(name);
    }

    private static void define(Map<String, int[]> entities, String entityName, int... codepoints) {
        int[] prev = entities.put(entityName, codepoints);
        assert prev == null : "Duplicate entity name: " + entityName;
    }

    /**
     * Returns the decimal character reference(s) for the given HTML entity name.
     *
     * @param name e.g. 'nbsp'
     * @return format: '{@code &#1234;}', or null if unknown
     */
    public static @Nullable String getDecimalReplacement(String name) {
        int[] codepoints = Holder.ENTITIES.get(name);
        if (codepoints == null)
            return null;
        return Arrays.stream(codepoints).mapToObj(cp -> "&#" + cp + ";").collect(Collectors.joining());
    }

